class EnvVarFileTest(unittest.TestCase):
    VALUES = {
        'PLAIN': 'value',
        'DOLLAR': 'pa$$word$HOME',
        'BACKTICK': 'a`id`b',
        'SUBST': '$(id)',
        'DQUOTE': 'say "hi"',
        'SQUOTE': "it's",
        'BACKSLASH': 'C:\\temp\\',
        'EQUALS': 'a=b=c',
        'SPACES': '  leading and trailing  ',
        'EMPTY': '',
    }

    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix='restic-env-test-')
        self.addCleanup(shutil.rmtree, self.dir, True)
        config = {'envvars': {'envvar': [
            {'envname': k, 'envvalue': v, 'reporef': 'shared'}
            for k, v in self.VALUES.items()]}}
        self.file = os.path.join(self.dir, 'restic-envvar-shared')
        with open(self.file, 'w') as f:
            f.write(render('etc-restic_envvar.j2', config=config, repouuid='shared'))

    def test_sourced_by_bash_like_the_scripts(self):
        names = ' '.join(self.VALUES)
        script = ('set -a; source "$1"; set +a; for n in %s; do '
                  'printf "%%s=%%s\\0" "$n" "${!n}"; done' % names)
        out = subprocess.run(['bash', '-c', script, 'bash', self.file],
                             capture_output=True, text=True, check=True).stdout
        got = dict(item.split('=', 1) for item in out.split('\0') if item)
        self.assertEqual(got, self.VALUES)

    @unittest.skipUnless(shutil.which('php') and
                         os.path.exists('/usr/share/php/openmediavault/autoloader.inc'),
                         'php / openmediavault PHP library not available')
    def test_loaded_by_omv_process_like_the_rpc_service(self):
        # setEnvFromFile() + getCommandLine() is how the RPC service uses
        # the file: each line becomes an unquoted `export NAME=value;`.
        php = r'''
            require_once "openmediavault/autoloader.inc";
            require_once "openmediavault/functions.inc";
            $p = new \OMV\System\Process(["env", "-0"]);
            $p->setEnvFromFile($argv[1]);
            passthru($p->getCommandLine(), $rc);
            exit($rc);
        '''
        out = subprocess.run(['php', '-r', php, self.file], capture_output=True,
                             text=True, check=True).stdout
        env = dict(item.split('=', 1) for item in out.split('\0') if '=' in item)
        for k, v in self.VALUES.items():
            if v == '':
                continue  # Process::setEnv() drops empty values
            self.assertEqual(env.get(k), v, k)


class EnvVarFileInvalidEntriesTest(unittest.TestCase):
    """Entries stored before validation existed must not break the file."""

    INVALID = [('MY-VAR', 'x'), ('A=B', 'x'), ('RESTIC_TEST_NL', 'a\nb'),
               ('1ABC', 'x'), ('A B', 'x'), ('ÄÖ', 'x'), ('CR', 'a\rb')]

    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix='restic-env-test-')
        self.addCleanup(shutil.rmtree, self.dir, True)
        entries = [('GOOD_BEFORE', 'one')] + self.INVALID + [('GOOD_AFTER', 'two')]
        config = {'envvars': {'envvar': [
            {'envname': k, 'envvalue': v, 'reporef': 'shared'} for k, v in entries]}}
        self.file = os.path.join(self.dir, 'restic-envvar-shared')
        with open(self.file, 'w') as f:
            f.write(render('etc-restic_envvar.j2', config=config, repouuid='shared'))

    def test_comment_lines_have_no_equals_sign(self):
        # PHP's setEnvFromFile() turns any line containing "=" into an
        # `export ...;` statement, comment lines included.
        with open(self.file) as f:
            for line in f:
                if line.lstrip().startswith('#'):
                    self.assertNotIn('=', line)

    def test_invalid_entries_skipped_for_bash(self):
        p = subprocess.run(
            ['bash', '-c', 'set -a; source "$1"; set +a; printf "%s|%s" "$GOOD_BEFORE" "$GOOD_AFTER"',
             'bash', self.file], capture_output=True, text=True)
        self.assertEqual(p.stderr, '')
        self.assertEqual(p.stdout, 'one|two')

    @unittest.skipUnless(shutil.which('php') and
                         os.path.exists('/usr/share/php/openmediavault/autoloader.inc'),
                         'php / openmediavault PHP library not available')
    def test_invalid_entries_skipped_for_omv_process(self):
        php = r'''
            require_once "openmediavault/autoloader.inc";
            require_once "openmediavault/functions.inc";
            $p = new \OMV\System\Process(["printenv", "GOOD_AFTER"]);
            $p->setEnvFromFile($argv[1]);
            passthru($p->getCommandLine(), $rc);
            exit($rc);
        '''
        p = subprocess.run(['php', '-r', php, self.file], capture_output=True, text=True)
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)
        self.assertEqual(p.stdout.strip(), 'two')


class DefaultStateTest(unittest.TestCase):
    """Render default.sls with stubbed Salt functions and inspect the result."""

    def render_state(self, snapshots=(), restoretests=()):
        r = repo()
        config = {
            'settings': {'cachedir': '', 'exclude': '', 'excludecaches': False},
            'repos': {'repo': [r]},
            'snapshots': {'snapshot': list(snapshots)},
            'restoretests': {'restoretest': list(restoretests)},
            'envvars': {'envvar': []},
        }
        data = {
            'conf.service.restic': config,
            'conf.system.filesystem.mountpoint': [],
            'conf.system.sharedfolder': [],
        }
        env = make_env(SALT_DIR)
        env.globals.update(
            salt={'omv_conf.get': lambda key: data[key],
                  'pillar.get': lambda key, default=None: default},
            tpldir='omv/deploy/restic')
        return yaml.safe_load(env.get_template('default.sls').render())

    def cron_exprs(self, state):
        for arg in state['configure_restic_cron']['file.managed']:
            if 'context' in arg:
                return [j['cronexpr'] for j in arg['context']['jobs']]
        self.fail('no cron context')

    def test_every_n_schedules(self):
        cases = [
            (dict(minute='15', everynminute=True), '*/15 0 * * *'),
            (dict(minute='*', everynminute=True), '* 0 * * *'),
            (dict(minute='0', everynminute=True), '0 0 * * *'),
            (dict(minute='0,30', everynminute=True), '0,30 0 * * *'),
            (dict(minute='0,30', everynminute=False), '0,30 0 * * *'),
            (dict(hour='6', everynhour='1'), '0 */6 * * *'),
            (dict(hour='6', everynhour='0'), '0 6 * * *'),
            (dict(dayofmonth='2', everyndayofmonth=True, dayofweek='1'), '0 0 */2 * 1'),
        ]
        for kw, expected in cases:
            with self.subTest(kw=kw):
                state = self.render_state(snapshots=[job(execution='exactly', **kw)],
                                          restoretests=[job(execution='exactly', **kw)])
                self.assertEqual(self.cron_exprs(state)[:2], [expected, expected])

    def test_job_script_gets_hash_file(self):
        state = self.render_state(snapshots=[job()])
        ctx = [a for a in state['configure_restic_job_script_' + job()['uuid']]['file.managed']
               if 'context' in a][0]['context']
        self.assertEqual(ctx['hashfile'],
                         '/var/lib/openmediavault/restic/hash-' + job()['uuid'])


