class Sandbox:
    """A temporary directory the generated scripts are redirected into."""

    def __init__(self):
        self.dir = tempfile.mkdtemp(prefix='restic-tpl-test-')
        for d in ('log', 'lock', 'etc', 'bin', 'lib', 'src'):
            os.makedirs(os.path.join(self.dir, d))
        self.restic = os.path.join(self.dir, 'bin', 'restic')
        with open(self.restic, 'w') as f:
            f.write(FAKE_RESTIC)
        os.chmod(self.restic, 0o755)
        self.log = os.path.join(self.dir, 'log', 'restic.log')
        self.hashfile = os.path.join(self.dir, 'lib', 'hash-job')

    def path(self, *p):
        return os.path.join(self.dir, *p)

    def cleanup(self):
        shutil.rmtree(self.dir, ignore_errors=True)

    def install(self, script, name='script.sh'):
        """Rewrite the hard-coded system paths and write the script."""
        for old, new in (
            ('/var/log/restic', self.path('log')),
            ('/run/lock', self.path('lock')),
            ('/etc/restic', self.path('etc')),
            ('/usr/bin/restic', self.restic),
        ):
            script = script.replace(old, new)
        target = self.path(name)
        with open(target, 'w') as f:
            f.write(script)
        os.chmod(target, 0o700)
        return target

    def run(self, script_path, cron=False, **env):
        e = dict(os.environ, SANDBOX=self.dir)
        e.update({k: str(v) for k, v in env.items()})
        if cron:
            # Exactly how the cron entry runs it (see etc-cron_restic.j2).
            cmd = ['bash', '-c', '"$0" >/dev/null 2>>"$1"', script_path, self.log]
        else:
            cmd = [script_path]
        p = subprocess.run(cmd, env=e, cwd=self.dir, capture_output=True,
                           text=True, timeout=60)
        return p.returncode

    def read(self, *p):
        try:
            with open(self.path(*p)) as f:
                return f.read()
        except FileNotFoundError:
            return ''


class ScriptTestCase(unittest.TestCase):
    def setUp(self):
        self.sb = Sandbox()
        self.addCleanup(self.sb.cleanup)

    def assertSyntaxOk(self, script):
        p = subprocess.run(['bash', '-n'], input=script, text=True,
                           capture_output=True)
        self.assertEqual(p.returncode, 0, p.stderr)

    def assertNoInjection(self, script_path, name, **env):
        rc = self.sb.run(script_path, **env)
        self.assertEqual(rc, 0, self.sb.read('log', 'restic.log'))
        self.assertFalse(os.path.exists(self.sb.path('MARK')),
                         'command substitution in a name was executed')
        self.assertIn(name.replace('{mark}', 'MARK'), self.sb.read('log', 'restic.log'))


class BackupJobScriptTest(ScriptTestCase):
    def render_job(self, **kw):
        return render('restic-job.sh.j2', job=job(**kw), repo=repo(),
                      repo_path=self.sb.path('repo'),
                      source_paths=[self.sb.path('src')], cachedir='',
                      excludefile='', excludecaches=False,
                      hashfile=self.sb.hashfile)

    def test_nasty_job_names_are_quoted(self):
        for name in NASTY_NAMES:
            with self.subTest(name=name):
                self.sb.cleanup()
                self.sb = Sandbox()
                script = self.render_job(name=name.replace('{mark}', 'MARK'))
                self.assertSyntaxOk(script)
                self.assertNoInjection(self.sb.install(script), name)

    def test_name_with_newline_does_not_break_script(self):
        script = self.render_job(name='line1\nline2')
        self.assertSyntaxOk(script)
        self.assertEqual(self.sb.run(self.sb.install(script)), 0)

    def test_password_is_passed_verbatim(self):
        self.sb.run(self.sb.install(self.render_job()))
        self.assertIn('RESTIC_PASSWORD=' + repo()['passphrase'] + '\n',
                      self.sb.read('restic-env'))

    def test_failed_backup_skips_retention_and_fails(self):
        rc = self.sb.run(self.sb.install(self.render_job()), FAKE_BACKUP_EXIT=3)
        self.assertEqual(rc, 3)
        calls = self.sb.read('restic-calls')
        self.assertIn('backup', calls)
        self.assertNotIn('forget', calls)
        self.assertFalse(os.path.exists(self.sb.hashfile))

    def test_successful_backup_records_snapshot_id_and_applies_retention(self):
        rc = self.sb.run(self.sb.install(self.render_job()))
        self.assertEqual(rc, 0)
        self.assertEqual(self.sb.read('lib', 'hash-job'), '0123abcd')
        forget = [l for l in self.sb.read('restic-calls').splitlines()
                  if l.startswith('forget')]
        self.assertEqual(len(forget), 1)
        self.assertIn('--keep-daily 7', forget[0])
        self.assertIn('--path ' + self.sb.path('src'), forget[0])

    def test_log_lines_are_not_duplicated_when_run_from_cron(self):
        rc = self.sb.run(self.sb.install(self.render_job()), cron=True)
        self.assertEqual(rc, 0)
        lines = [l for l in self.sb.read('log', 'restic.log').splitlines() if l]
        self.assertTrue(lines)
        self.assertEqual(len(lines), len(set(lines)),
                         'log contains duplicated lines:\n' + '\n'.join(lines))
        self.assertEqual(sum('Starting backup job' in l for l in lines), 1)

    def test_prescript_failure_skips_backup(self):
        rc = self.sb.run(self.sb.install(self.render_job(prescript='exit 4')))
        self.assertEqual(rc, 4)
        self.assertNotIn('backup', self.sb.read('restic-calls'))


