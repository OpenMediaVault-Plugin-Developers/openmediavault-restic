#!/usr/bin/env python3
"""Tests for the Salt templates of openmediavault-restic.

Usage: python3 -I tests/test-templates.py   (no root needed)

The templates are rendered with plain Jinja2 (plus stubs for the few Salt
helpers they use). The generated shell scripts are then actually run in a
temporary sandbox: the absolute paths they hard-code are rewritten to
sandbox paths, and /usr/bin/restic is replaced by a stub that records its
arguments and exits with a configurable status.

Requirements: python3-jinja2, python3-yaml, bash, flock. The env var test
also uses php and the openmediavault PHP library, and is skipped without
them.
"""

import json
import os
import shutil
import subprocess
import tempfile
import unittest

import jinja2
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SALT_DIR = os.path.join(ROOT, 'srv', 'salt', 'omv', 'deploy', 'restic')
FILES_DIR = os.path.join(SALT_DIR, 'files')

PILLAR = {'headers': {
    'auto_generated': '# This file is auto-generated by openmediavault',
    'warning': '# WARNING: Do not edit this file, your changes will get lost.',
}}

# Names that break or inject into a script unless they are quoted properly.
NASTY_NAMES = [
    'job "with" quotes',
    "it's a job",
    'unbalanced "quote',
    'subst $(touch {mark}) here',
    'backtick `touch {mark}` here',
    'dollar $HOME and \\ backslash',
]

FAKE_RESTIC = r'''#!/bin/bash
printf '%s\n' "$*" >> "$SANDBOX/restic-calls"
printf 'RESTIC_PASSWORD=%s\n' "$RESTIC_PASSWORD" >> "$SANDBOX/restic-env"
case "$1" in
    backup)
        echo "open repository"
        [ "${FAKE_BACKUP_EXIT:-0}" -eq 0 ] && echo "snapshot 0123abcd saved"
        exit "${FAKE_BACKUP_EXIT:-0}" ;;
    restore) exit "${FAKE_RESTORE_EXIT:-0}" ;;
    check)   exit "${FAKE_CHECK_EXIT:-0}" ;;
    forget)  exit "${FAKE_FORGET_EXIT:-0}" ;;
esac
exit 0
'''


def make_env(loader_dir):
    env = jinja2.Environment(
        loader=jinja2.FileSystemLoader(loader_dir),
        extensions=['jinja2.ext.do'],
        keep_trailing_newline=True,
    )
    env.filters['json'] = json.dumps
    env.filters['to_bool'] = lambda v: str(v).lower() in ('1', 'true', 'yes', 'on')
    env.globals['pillar'] = PILLAR
    return env


def render(name, **context):
    return make_env(FILES_DIR).get_template(name).render(**context)


